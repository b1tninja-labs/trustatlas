"""Probe every candidate trust-anchor source and write a catalog artifact.

This is trustatlas P1 (`PLAN.md`). It exists because the source table written by hand got six of fourteen URLs
wrong: the catalog is therefore generated by asking, and every attempt is recorded, including the failures. A
source is only a source when a probe says 200 and reports how many bytes and which hash it saw.

Stdlib only, no parsing, and no claims about content beyond "this many PEM blocks were in what I downloaded".
Certificate parsing is `asn1core`'s job; this records where bytes came from.
"""

